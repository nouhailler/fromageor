#!/usr/bin/env node
// Même enrichissement Wikipédia que scripts/enrich-wikipedia.mjs, mais pour
// les fromages ajoutés à la main (src/data/cheeses-extra.ts).
//
// Ce fichier-là est écrit à la main : on n'y touche donc pas, et le résultat
// atterrit dans src/data/cheeses-extra-media.ts, un fichier généré et indexé
// par identifiant, que dataset.ts recolle sur les fromages correspondants.
//
// Usage: node --experimental-strip-types scripts/enrich-wikipedia-extra.mjs [--id <cheese-id>]
//   (le flag sert à importer directement le .ts des fromages)
import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
import { enrichCheese } from './enrich-wikipedia.mjs'

const __dirname = path.dirname(url.fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')
const mediaPath = path.join(repoRoot, 'src/data/cheeses-extra-media.ts')

const HEADER = `// GENERATED by scripts/enrich-wikipedia-extra.mjs — ne pas éditer à la main.
// Photos et résumés Wikipédia des fromages de cheeses-extra.ts, tenus à part
// pour que le fichier écrit à la main reste lisible. Recollés dans dataset.ts.
import type { CheeseImage, CheeseWikipedia } from './cheese.types'

export interface CheeseMedia {
  image?: CheeseImage
  wikipedia?: CheeseWikipedia
  galleryImages?: CheeseImage[]
}

export const EXTRA_MEDIA: Record<string, CheeseMedia> = `

function readExistingMedia() {
  const text = fs.readFileSync(mediaPath, 'utf8')
  return JSON.parse(text.slice(text.indexOf('= {') + 2))
}

async function main() {
  const idArg = process.argv.includes('--id') ? process.argv[process.argv.indexOf('--id') + 1] : null
  const { EXTRA_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-extra.ts'))
  const { BFC_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-bourgogne-franche-comte.ts'))
  const { BRETAGNE_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-bretagne.ts'))
  const { CVL_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-centre-val-de-loire.ts'))
  const { NORMANDIE_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-normandie.ts'))
  const { HDF_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-hauts-de-france.ts'))
  const { CORSE_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-corse.ts'))
  const { GRAND_EST_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-grand-est.ts'))
  const { IDF_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-ile-de-france.ts'))
  const { OCCITANIE_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-occitanie.ts'))
  const { NA_CHEESES } = await import(path.join(repoRoot, 'src/data/cheeses-nouvelle-aquitaine.ts'))
  const manuels = [
    ...EXTRA_CHEESES,
    ...BFC_CHEESES,
    ...BRETAGNE_CHEESES,
    ...CVL_CHEESES,
    ...NORMANDIE_CHEESES,
    ...HDF_CHEESES,
    ...CORSE_CHEESES,
    ...GRAND_EST_CHEESES,
    ...IDF_CHEESES,
    ...OCCITANIE_CHEESES,
    ...NA_CHEESES,
  ]

  // Avec --id on ne retouche qu'une entrée : on repart de l'existant pour ne
  // pas effacer les autres.
  const media = idArg && fs.existsSync(mediaPath) ? readExistingMedia() : {}
  for (const cheese of manuels) {
    if (idArg && cheese.id !== idArg) continue
    const enriched = await enrichCheese(cheese)
    const entry = {}
    if (enriched.image) entry.image = enriched.image
    if (enriched.wikipedia) entry.wikipedia = enriched.wikipedia
    if (enriched.galleryImages?.length) entry.galleryImages = enriched.galleryImages
    // Une entrée vide efface l'ancienne : une correction du script peut faire
    // disparaître un appariement erroné, il ne doit pas survivre dans le fichier.
    if (Object.keys(entry).length) media[cheese.id] = entry
    else delete media[cheese.id]
    await new Promise((r) => setTimeout(r, 200))
  }

  fs.writeFileSync(mediaPath, `${HEADER}${JSON.stringify(media, null, 2)}\n`)
  const withPhoto = Object.values(media).filter((m) => m.image).length
  console.log(
    `\nÉcrit ${path.relative(repoRoot, mediaPath)} : ${Object.keys(media).length}/${manuels.length} fromages enrichis, dont ${withPhoto} avec photo.`,
  )
}

main()
