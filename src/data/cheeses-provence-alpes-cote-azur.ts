// en trois pays fromagers sans grand rapport entre eux : les Alpes du Sud
// (Champsaur, Dévoluy, Queyras, Ubaye), pays de vache et de coopératives
// laitières ; la Provence des chèvres, du plateau d'Albion aux Alpilles, où
// le banon est la seule appellation ; et la Provence des fromages forts,
// ces pots de restes fermentés que chaque pays a nommés à sa façon —
// cachaille, cachat, brous, coussignous, bosson macéré — et qui pèsent ici
// plus lourd que partout ailleurs en France.
//
// Les deux AOP de la région sont le banon (AOC le 23 juillet 2003, première
// appellation fromagère de PACA) et la brousse du Rove (AOC le 31 mai 2018).
// Les deux figurent dans la liste officielle des AOC et AOP laitières
// françaises.
//
// L'aire du banon est à cheval sur deux régions, comme le bleu de Gex : sur
// les 179 communes du cahier des charges, 111 sont dans les
// Alpes-de-Haute-Provence et 33 dans les Hautes-Alpes, mais 21 sont dans la
// Drôme, donc en Auvergne-Rhône-Alpes. On tranche pour PACA, où se trouvent
// le village qui donne son nom au fromage et 144 communes sur 179.
//
// La tomme du Champsaur n'est pas ici : elle vient du jeu généré, où elle
// était rangée en Auvergne-Rhône-Alpes malgré son département (05). Elle
// rejoint PACA par une entrée dans EXTRA_REGION_OVERRIDES, comme le bleu des
// Causses et le laguiole avant elle.
//
// Ce qui n'est pas ici et pourrait s'y attendre :
//   — le picodon et le saint-félicien, donnés « vallée du Rhône,
//     Drôme/Ardèche » par le jeu généré : ils restent en
//     Auvergne-Rhône-Alpes, c'est correct ;
//   — la brousse tout court, que l'administration française classe comme
//     produit laitier et non comme fromage (c'est une recuite de
//     lactosérum) : seule la brousse du Rove, faite de lait entier et non de
//     lactosérum, est un fromage au sens réglementaire, et c'est elle qui a
//     l'AOP ;
//   — le rovethym, dont le seul article n'a pour source qu'une fiche de
//     catalogue d'affineur, insuffisant pour écrire une fiche vérifiable ;
//   — les tomes de Tende, de la Vésubie, des Vigneaux et du Queyras, citées
//     par l'article de la tome du Champsaur comme des variantes de celle-ci
